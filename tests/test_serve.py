"""Tests for the live server (`cosmoforge serve`) and its /api/expand endpoint.

A scripted provider stands in for a real model: it reads the allowed child kinds
out of the request payload and answers in the exact JSON shape the server
expects, so the whole round-trip is exercised offline.
"""
from __future__ import annotations

import json
import shutil
import tempfile
import threading
import unittest
import urllib.error
import urllib.request

from cosmoforge import Scenario
from cosmoforge.providers.base import LLMResponse, Provider
from cosmoforge.serve import make_server


class ScriptedProvider(Provider):
    """Answers with one child of the first allowed kind."""

    name = "scripted"
    label = "Scripted (test)"
    requires_key = False

    def _complete(self, messages, temperature, max_tokens):
        payload = json.loads(messages[-1].content)
        allowed = payload.get("allowed_child_kinds") or []
        children = []
        if allowed:
            children.append(
                {
                    "label": "A new " + allowed[0],
                    "kind": allowed[0],
                    "detail": "generated by the scripted provider",
                    "meta": {"severity": 0.5, "note": "test"},
                }
            )
        return LLMResponse(
            text=json.dumps({"narrative": "续写：一条新的支线由此展开。", "children": children}),
            provider=self.name,
            model="scripted-1",
        )


def _post(port, path, payload):
    request = urllib.request.Request(
        f"http://127.0.0.1:{port}{path}",
        data=json.dumps(payload).encode("utf-8"),
        headers={"Content-Type": "application/json"},
        method="POST",
    )
    try:
        with urllib.request.urlopen(request, timeout=5) as resp:
            return resp.status, json.loads(resp.read().decode("utf-8"))
    except urllib.error.HTTPError as exc:
        return exc.code, json.loads(exc.read().decode("utf-8"))


def _post_stream(port, path, payload):
    request = urllib.request.Request(
        f"http://127.0.0.1:{port}{path}",
        data=json.dumps(payload).encode("utf-8"),
        headers={"Content-Type": "application/json"},
        method="POST",
    )
    with urllib.request.urlopen(request, timeout=10) as resp:
        return resp.status, resp.read().decode("utf-8")


def _get(port, path):
    with urllib.request.urlopen(f"http://127.0.0.1:{port}{path}", timeout=5) as resp:
        return resp.status, resp.read().decode("utf-8")


class ServeTest(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        scenario = Scenario.demo().with_overrides(universes=2, seed=5, branching=0.0)
        cls.archive_dir = tempfile.mkdtemp(prefix="cosmoforge-archives-")
        cls.server, cls.state = make_server(
            scenario, ScriptedProvider(), host="127.0.0.1", port=0,
            title="Test Cosmos", archive_dir=cls.archive_dir,
        )
        cls.port = cls.server.server_address[1]
        cls.thread = threading.Thread(target=cls.server.serve_forever, daemon=True)
        cls.thread.start()

    @classmethod
    def tearDownClass(cls):
        cls.server.shutdown()
        cls.server.server_close()
        shutil.rmtree(cls.archive_dir, ignore_errors=True)

    # -- helpers ----------------------------------------------------------
    def _find(self, kind):
        stack = [self.state.tree]
        while stack:
            node = stack.pop()
            if node.kind == kind:
                return node
            stack.extend(node.children)
        return None

    # -- tests ------------------------------------------------------------
    def test_index_is_live(self):
        status, html = _get(self.port, "/")
        self.assertEqual(status, 200)
        self.assertIn("/static/app.js", html)
        self.assertIn("/static/styles.css", html)
        self.assertIn('id="timeline"', html)
        self.assertIn('id="zoom"', html)
        self.assertIn('id="seed"', html)
        self.assertIn('id="archive-modal"', html)
        self.assertNotIn("const DATA =", html)   # front end is data-free

    def test_bootstrap_returns_tree_and_live_flag(self):
        status, body = _get(self.port, "/api/bootstrap")
        self.assertEqual(status, 200)
        payload = json.loads(body)
        self.assertTrue(payload["live"])
        self.assertEqual(payload["title"], "Test Cosmos")
        self.assertEqual(payload["tree"]["id"], "root")
        self.assertIsInstance(payload["seed"], int)

    def test_static_frontend_assets_are_served_separately(self):
        status, js = _get(self.port, "/static/app.js")
        self.assertEqual(status, 200)
        self.assertIn("/api/expand/stream", js)
        self.assertIn("pointerdown", js)
        self.assertIn("evolveOnce", js)
        self.assertIn("regenerateFromSeed", js)
        self.assertIn("saveArchive", js)
        status, css = _get(self.port, "/static/styles.css")
        self.assertEqual(status, 200)
        self.assertIn("touch-action:none", css)

    def test_expand_adds_children_of_allowed_kind(self):
        planet = self._find("planet")
        before = len(planet.children)
        status, data = _post(self.port, "/api/expand", {"id": planet.id, "action": "expand"})
        self.assertEqual(status, 200)
        self.assertGreaterEqual(data["added"], 1)
        self.assertEqual(data["children"][0]["kind"], "event")
        self.assertEqual(len(planet.children), before + data["added"])
        self.assertIn("续写", data["narrative"])

    def test_continue_appends_narrative(self):
        node = self._find("universe")
        original = node.detail
        status, data = _post(self.port, "/api/expand", {"id": node.id, "action": "continue"})
        self.assertEqual(status, 200)
        self.assertGreater(len(data["narrative"]), len(original))
        self.assertTrue(data["narrative"].startswith(original[:20]))

    def test_stream_expand_emits_progressive_events(self):
        planet = self._find("planet")
        status, body = _post_stream(
            self.port, "/api/expand/stream", {"id": planet.id, "action": "expand"}
        )
        self.assertEqual(status, 200)
        self.assertIn("event: phase", body)
        self.assertIn("event: delta", body)
        self.assertIn("event: node", body)
        self.assertIn("event: done", body)
        self.assertIn('"kind": "event"', body)
        self.assertIn("续写", body)

    def test_regenerate_seed_is_deterministic(self):
        status, first = _post(self.port, "/api/regenerate", {"seed": 777})
        self.assertEqual(status, 200)
        self.assertEqual(first["seed"], 777)
        status, second = _post(self.port, "/api/regenerate", {"seed": 777})
        self.assertEqual(status, 200)
        self.assertEqual(first["tree"], second["tree"])
        status, other = _post(self.port, "/api/regenerate", {"seed": 778})
        self.assertEqual(status, 200)
        self.assertNotEqual(first["tree"], other["tree"])

    def test_regenerate_rejects_bad_seed(self):
        status, data = _post(self.port, "/api/regenerate", {"seed": "not-a-number"})
        self.assertEqual(status, 400)
        self.assertIn("seed", data["error"])

    def test_save_list_load_and_download_archive(self):
        _, tree_body = _get(self.port, "/api/tree")
        saved_tree = json.loads(tree_body)
        status, saved = _post(self.port, "/api/save", {"name": "unit archive"})
        self.assertEqual(status, 200)
        self.assertTrue(saved["ok"])
        self.assertEqual(saved["name"], "unit archive")

        status, listing = _get(self.port, "/api/archives")
        self.assertEqual(status, 200)
        ids = [item["id"] for item in json.loads(listing)["archives"]]
        self.assertIn(saved["id"], ids)

        _post(self.port, "/api/regenerate", {"seed": 12345})
        status, loaded = _post(self.port, "/api/load", {"id": saved["id"]})
        self.assertEqual(status, 200)
        self.assertEqual(loaded["tree"], saved_tree)
        self.assertEqual(loaded["seed"], saved["seed"])

        status, body = _get(self.port, f"/api/archive?id={saved['id']}")
        self.assertEqual(status, 200)
        self.assertEqual(json.loads(body)["id"], saved["id"])

    def test_archive_rejects_unknown_id(self):
        status, data = _post(self.port, "/api/load", {"id": "does-not-exist"})
        self.assertEqual(status, 400)
        self.assertIn("not found", data["error"])

    def test_unknown_node_is_400(self):
        status, data = _post(self.port, "/api/expand", {"id": "nope:9999", "action": "expand"})
        self.assertEqual(status, 400)
        self.assertIn("unknown node", data["error"])

    def test_epoch_cannot_expand(self):
        epoch = self._find("epoch")
        status, data = _post(self.port, "/api/expand", {"id": epoch.id, "action": "expand"})
        self.assertEqual(status, 400)
        self.assertIn("cannot be expanded", data["error"])

    def test_health_reports_provider(self):
        status, body = _get(self.port, "/api/health")
        self.assertEqual(status, 200)
        payload = json.loads(body)
        self.assertTrue(payload["ok"])
        self.assertEqual(payload["provider"]["provider"], "scripted")


if __name__ == "__main__":  # pragma: no cover
    unittest.main()
